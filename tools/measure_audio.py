"""Generate firmware playback durations from the actual SD-card MP3 files.

Run again after replacing any MP3, then recompile the sketch.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import math
import subprocess

ROOT = Path(__file__).resolve().parents[1]

def duration(path):
    result = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                             "-of", "default=noprint_wrappers=1:nokey=1", str(path)],
                            capture_output=True, text=True, check=True)
    return math.ceil(float(result.stdout.strip()) * 1000)

def main():
    lines = ["// Generated by tools/measure_audio.py; durations in milliseconds.",
             "#pragma once", "#include <stdint.h>"]
    for folder, count, name in [(1, 26, "LETTER_AUDIO_MS"), (2, 255, "WORD_AUDIO_MS"), (3, 13, "PROMPT_AUDIO_MS")]:
        with ThreadPoolExecutor(max_workers=6) as pool:
            values = list(pool.map(duration, [ROOT / f"{folder:02d}" / f"{n:03d}.mp3" for n in range(1, count+1)]))
        lines.append(f"constexpr uint32_t {name}[{count}] = {{")
        lines.extend("  " + ", ".join(map(str, values[i:i+10])) + "," for i in range(0, count, 10))
        lines.append("};")
        print(f"Folder {folder:02d}: {count} files measured; maximum {max(values)} ms")
    (ROOT / "Adaptive_braille_project" / "AudioDurations.h").write_text("\n".join(lines)+"\n", encoding="utf-8")

if __name__ == "__main__":
    main()
